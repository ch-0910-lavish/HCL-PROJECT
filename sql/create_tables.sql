-- CREATE TABLE

CREATE TABLE SPOTIFY_TRACKS(
    SONG VARCHAR2(200),
    ARTIST VARCHAR2(100),
    GENRE VARCHAR2(100),
    YEAR NUMBER,
    STREAMS NUMBER,
    POPULARITY NUMBER
);

-- TOP ARTISTS QUERY

SELECT
ARTIST,
COUNT(*) AS TOTAL_SONGS
FROM SPOTIFY_TRACKS
GROUP BY ARTIST
ORDER BY TOTAL_SONGS DESC;

-- TOP GENRES QUERY

SELECT
GENRE,
COUNT(*) AS TOTAL_TRACKS
FROM SPOTIFY_TRACKS
GROUP BY GENRE;

-- VIEW CREATION

CREATE VIEW ARTIST_SUMMARY AS
SELECT
ARTIST,
COUNT(*) TOTAL_SONGS
FROM SPOTIFY_TRACKS
GROUP BY ARTIST;

SELECT * FROM ARTIST_SUMMARY;

-- POPULARITY CHECK

SELECT
ARTIST,
AVG(POPULARITY) AVG_POPULARITY
FROM SPOTIFY_TRACKS
GROUP BY ARTIST;